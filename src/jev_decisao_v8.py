def perguntas_nouls():
    q = {}
    for o in OPCOES:
        q[f"{o}_ataca_falha"] = {
            "type": "noul",
            "instructions": f"Does `options.{o}` directly address at least one of the failure findings listed in `teacher_findings_4b_finetuned`?",
            "criteria": {
                "true": "The option changes something that causes one of the listed failures.",
                "false": "The option leaves the cause of the listed failures untouched, or only changes something unrelated to them.",
            },
        }
        q[f"{o}_mensuravel_hoje"] = {
            "type": "noul",
            "instructions": f"Could the effect of `options.{o}` on teacher-judged question quality be reliably detected using only what `measurement_today` says exists now?",
            "criteria": {
                "true": "The effect can be told apart from noise with the instruments that exist now.",
                "false": "The instruments that exist now are too noisy or too narrow to detect the effect.",
            },
        }
    q["medicao_e_precondicao"] = {
        "type": "noul",
        "instructions": "Given `measurement_today`, should a more precise measurement be in place before judging whether any training change improved teacher-judged quality?",
        "criteria": {
            "true": "Differences of the expected size would fall inside the noise of the current instruments.",
            "false": "The current instruments are precise enough to judge training changes.",
        },
    }
    q["hiperparametros_tem_evidencia"] = {
        "type": "noul",
        "instructions": "Does `training_setup` report evidence that changing hyperparameters has an effect larger than the noise between training seeds?",
        "criteria": {"true": "The state reports such evidence.", "false": "The state does not report such evidence."},
    }
    return q


def pergunta_escolha(ordem):
    return {
        "type": "choice",
        "instructions": "Given the facts in the state, which single option in `options` is the best first step to improve the quality of questions the 4B model writes, as judged by the teacher?",
        "criteria": {o: OPCOES[o] for o in ordem},
    }


def main():
    ordens = {
        "direta": list("ABCDEF"),
        "inversa": list("FEDCBA"),
        "rotacao": list("DEFABC"),
        "embaralhada": list("CFAEDB"),
    }
    questoes = perguntas_nouls()
    for nome, ordem in ordens.items():
        questoes[f"primeiro_passo__{nome}"] = pergunta_escolha(ordem)
    resp = chamar(STATE, questoes)
    ans = resp["answers"]

    nouls = {k: v["noul"] for k, v in ans.items() if v["type"] == "noul"}
    escolhas = {k.split("__")[1]: v for k, v in ans.items() if k.startswith("primeiro_passo__")}

    # composicao em codigo: P(ataca) * P(mensuravel) por opcao; custo vem dos fatos
    tabela = {}
    for o in OPCOES:
        ataca, mens = nouls[f"{o}_ataca_falha"], nouls[f"{o}_mensuravel_hoje"]
        tabela[o] = dict(ataca=round(ataca, 3), mensuravel=round(mens, 3),
                         valor=round(ataca * mens, 3), **CUSTO[o])
    votos = {}
    for nome, v in escolhas.items():
        votos.setdefault(v["choice"], []).append(nome)
    prob_media = {o: round(sum(v["probabilities"].get(o, 0) for v in escolhas.values()) / len(escolhas), 3)
                  for o in OPCOES}

    saida = dict(modelo=resp["model"], uso=resp["usage"], nouls=nouls, tabela=tabela, votos=votos,
                 confianca={n: round(v["confidence"], 3) for n, v in escolhas.items()},
                 probabilidade_media_primeiro_passo=prob_media,
                 escolha_por_ordem={n: v["choice"] for n, v in escolhas.items()})
    OUT.write_text(json.dumps(saida, ensure_ascii=False, indent=1))
    print(json.dumps(saida, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
